/* 🖼 The gallery panel's TARGET — the decidable half of "one panel, two scopes".
 *
 * The board opens the same panel on a checkpoint pill (one step) and on a run
 * card (every step of that run). Writing a second panel for the second scope
 * would have meant two grids over the same rows, two Select modes and two places
 * to keep the delete's promises true; they would agree on the day they shipped
 * and drift on the first change. So the panel takes a TARGET and asks this
 * module what that target means: which endpoints, which title, which copy, and —
 * for a run — how its groups are laid out.
 *
 * JSX-free on purpose: `node --test` does not parse JSX, and the things that
 * must not be eyeballed are exactly here — the ORDER of the step groups, which
 * of them open expanded, and the sentence that has to stay honest about what the
 * panel is not showing.
 */

/** 'run' | 'checkpoint'. A target with no step is a run — the panel never has to
 *  invent a scope from a missing field. */
export function galleryScope(target) {
  if (!target) return null;
  return target.kind === 'run' || target.step == null ? 'run' : 'checkpoint';
}

/** A stable identity for the open target, so the panel can reload when it
 *  changes and NOT when its host re-renders. */
export function galleryTargetKey(target) {
  if (!target) return '';
  return galleryScope(target) === 'run'
    ? `run:${target.recordId}`
    : `ck:${target.recordId}:${target.step}`;
}

/** {list, remove} — the two endpoints for this scope. The delete lives beside
 *  the read on purpose: a panel that could read one scope and delete in another
 *  is the bug this pairing makes unrepresentable. */
export function galleryEndpoints(target) {
  if (!target) return null;
  const rid = target.recordId;
  if (galleryScope(target) === 'run') {
    return { list: `/api/train/run/${rid}/images`,
      remove: `/api/train/run/${rid}/images/delete` };
  }
  return { list: `/api/train/checkpoint/${rid}/${target.step}/images`,
    remove: `/api/train/checkpoint/${rid}/${target.step}/images/delete` };
}

/** The panel's heading, split so the JSX can style the two halves. */
export function galleryHeading(target) {
  if (!target) return null;
  const rid = target.recordId;
  if (galleryScope(target) === 'run') {
    return { title: `Run #${rid}`, subtitle: 'every image, by step',
      aria: `All images generated by run ${rid}, grouped by step` };
  }
  const step = Number(target.step);
  return {
    title: `Step ${Number.isFinite(step) ? step.toLocaleString('en-US') : target.step}`,
    subtitle: `run #${rid}`,
    aria: `Images generated at step ${target.step}`,
  };
}

/** One group's label. `null` is not "no step" — it is "this run, and we do not
 *  know which of its checkpoints", which is a different and useful thing. */
export function stepGroupLabel(step) {
  if (step == null) return 'Step unknown';
  const n = Number(step);
  return `Step ${Number.isFinite(n) ? n.toLocaleString('en-US') : step}`;
}

/** Normalise the payload's groups for rendering. Steps arrive already ordered by
 *  the backend (descending, step-less last); this only fills in what the JSX
 *  should not compute — the label and a stable key. Defensive about a payload
 *  with no groups at all, because a run with nothing is a normal run. */
export function runGalleryGroups(data) {
  return (data?.groups || []).map((g, i) => ({
    key: g?.step == null ? 'unknown' : `s${g.step}`,
    step: g?.step ?? null,
    label: stepGroupLabel(g?.step),
    count: Number(g?.count) || 0,
    truncated: !!g?.truncated,
    images: g?.images || [],
    index: i,
  }));
}

/* How many groups open EXPANDED. A run can hold fourteen checkpoints; opening
   all of them at once is a wall of thumbnails and a grid that stutters on a
   phone. Three is what fits a first look — the most-trained checkpoints, which
   are the ones the panel exists to compare — and every other group still states
   its count in its header, so nothing is hidden, only folded. */
export const RUN_GALLERY_OPEN_GROUPS = 3;

/** The set of group keys that start OPEN. */
export function defaultOpenGroups(groups, howMany = RUN_GALLERY_OPEN_GROUPS) {
  const open = new Set();
  for (const g of (groups || []).slice(0, Math.max(0, howMany))) open.add(g.key);
  return open;
}

/** Every image currently laid out in the panel, flattened — what Select mode,
 *  "Select all" and the delete operate on. Only what is SHOWN: selecting an
 *  image the panel folded away or never fetched would arm a delete the user
 *  cannot see. */
export function visibleGalleryImages(groups, openKeys) {
  const out = [];
  for (const g of groups || []) {
    if (openKeys && !openKeys.has(g.key)) continue;
    for (const img of g.images || []) out.push(img);
  }
  return out;
}

/** The line under the header: what this panel holds, and what it is not showing.
 *  Truncation is STATED — a capped gallery that looks complete is a gallery that
 *  lies about the run. */
export function runGallerySummary(data) {
  const count = Number(data?.count) || 0;
  const shown = Number(data?.shown) || 0;
  const steps = (data?.groups || []).length;
  if (count === 0) {
    return 'Nothing generated from this run yet — tick a checkpoint below the card '
      + 'and run from the board.';
  }
  const head = `${count} image${count > 1 ? 's' : ''} across ${steps} step${
    steps > 1 ? 's' : ''}, most-trained first.`;
  return data?.truncated
    ? `${head} Showing the newest ${shown} — open a step in the Test Studio for the rest.`
    : head;
}

/** The run's checkpoint notes, newest step first.
 *
 *  Read from the PAYLOAD, not from the node's pills: a note is stored against
 *  (run, step) and outlives the file it describes, so a run whose saves have
 *  been cleaned off the disk has no pills left and would lose every note written
 *  about it. The node is only a fallback for a payload that predates the field.
 *  Steps that produced no image still appear — a note nobody can read is lost. */
export function checkpointNotes(data, node) {
  const fromPayload = data?.checkpoint_notes;
  if (Array.isArray(fromPayload)) {
    return fromPayload
      .filter((n) => (n?.note || '').trim())
      .map((n) => ({ step: n.step ?? null, note: n.note }));
  }
  return (node?.checkpoints || [])
    .filter((c) => (c?.note || '').trim())
    .map((c) => ({ step: c.step ?? null, note: c.note }))
    .sort((a, b) => (b.step ?? -1) - (a.step ?? -1));
}

/** The unlinked footnote. It counts images tied to NO run at all, so it is just
 *  as true at run scope as at checkpoint scope — only the word for what could
 *  not be found changes. The number does NOT include the "step unknown" group:
 *  those images found their run, which is why they left this counter. */
export function unlinkedNote(count, scope = 'checkpoint') {
  const n = Number(count) || 0;
  if (n <= 0) return null;
  const what = scope === 'run' ? 'a run' : 'a checkpoint';
  return `${n} older test image${n > 1 ? 's' : ''} could not be traced back to ${what} `
    + '(generated before the link was recorded, and the file name says nothing '
    + 'certain). They are kept, just not shown under a node — they are in the '
    + 'Test Studio.';
}
