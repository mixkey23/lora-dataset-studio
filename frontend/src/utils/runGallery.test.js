/* 🖼 One panel, two scopes — the decisions a screenshot cannot show.
 *
 * The run gallery is the checkpoint gallery with its scope widened, so what has
 * to be pinned is everything that would let the two drift or lie:
 *  (a) which endpoints a target resolves to — a panel that reads one scope and
 *      deletes in another is the bug this pairing exists to prevent;
 *  (b) the ORDER of the step groups, and that "step unknown" stays a real group
 *      rather than being folded into the honest-gap footnote;
 *  (c) that only what is LAID OUT can be selected — arming a delete for an image
 *      the panel folded away, or never fetched past the cap, is a silent wrong;
 *  (d) that truncation is SAID. A capped gallery that reads as complete lies
 *      about the run.
 */
import assert from 'node:assert/strict';
import test from 'node:test';

import {
  checkpointNotes, defaultOpenGroups, galleryEndpoints, galleryHeading, galleryScope,
  galleryTargetKey, runGalleryGroups, runGallerySummary, stepGroupLabel,
  unlinkedNote, visibleGalleryImages, RUN_GALLERY_OPEN_GROUPS,
} from './runGallery.js';

const RUN = { kind: 'run', recordId: 87 };
const CK = { recordId: 87, step: 2250 };

test('a target resolves to its scope, and a run is never mistaken for a step', () => {
  assert.equal(galleryScope(RUN), 'run');
  assert.equal(galleryScope(CK), 'checkpoint');
  assert.equal(galleryScope(null), null);
  // A malformed pill target (no step) degrades to the run, which shows MORE and
  // deletes within the same run — never the reverse.
  assert.equal(galleryScope({ recordId: 87 }), 'run');
});

test('read and delete endpoints always belong to the SAME scope', () => {
  assert.deepEqual(galleryEndpoints(RUN), {
    list: '/api/train/run/87/images',
    remove: '/api/train/run/87/images/delete',
  });
  assert.deepEqual(galleryEndpoints(CK), {
    list: '/api/train/checkpoint/87/2250/images',
    remove: '/api/train/checkpoint/87/2250/images/delete',
  });
  assert.equal(galleryEndpoints(null), null);
});

test('the target key changes with the target and not with a re-render', () => {
  assert.equal(galleryTargetKey(RUN), 'run:87');
  assert.equal(galleryTargetKey({ ...RUN }), 'run:87');
  assert.equal(galleryTargetKey(CK), 'ck:87:2250');
  assert.notEqual(galleryTargetKey(RUN), galleryTargetKey(CK));
});

test('the heading names the scope in English', () => {
  assert.deepEqual(galleryHeading(RUN),
    { title: 'Run #87', subtitle: 'every image, by step',
      aria: 'All images generated by run 87, grouped by step' });
  assert.equal(galleryHeading(CK).title, 'Step 2,250');
  assert.equal(galleryHeading(CK).subtitle, 'run #87');
});

test('a step-less group says "unknown", not "0" or nothing', () => {
  assert.equal(stepGroupLabel(3500), 'Step 3,500');
  assert.equal(stepGroupLabel(null), 'Step unknown');
  assert.equal(stepGroupLabel(undefined), 'Step unknown');
});

test('groups keep the backend order and get a stable key each', () => {
  const groups = runGalleryGroups({
    groups: [{ step: 3500, count: 2, images: [{ id: 1 }, { id: 2 }] },
      { step: 1000, count: 1, images: [{ id: 3 }] },
      { step: null, count: 4, truncated: true, images: [{ id: 4 }] }],
  });
  assert.deepEqual(groups.map((g) => g.key), ['s3500', 's1000', 'unknown']);
  assert.deepEqual(groups.map((g) => g.label),
    ['Step 3,500', 'Step 1,000', 'Step unknown']);
  assert.equal(groups[2].truncated, true);
  // A run with nothing is a normal run, not a crash.
  assert.deepEqual(runGalleryGroups(null), []);
  assert.deepEqual(runGalleryGroups({}), []);
});

test('only the most-trained groups open — the rest fold behind their counts', () => {
  const groups = runGalleryGroups({
    groups: [3500, 3000, 2500, 2000, 1500, 1000].map(
      (step) => ({ step, count: 30, images: [] })),
  });
  const open = defaultOpenGroups(groups);
  assert.equal(open.size, RUN_GALLERY_OPEN_GROUPS);
  assert.deepEqual([...open], ['s3500', 's3000', 's2500']);
  // A short run opens entirely; nothing is folded for the sake of it.
  assert.equal(defaultOpenGroups(groups.slice(0, 2)).size, 2);
});

test('selection can only ever reach what is laid out', () => {
  const groups = runGalleryGroups({
    groups: [{ step: 2000, count: 2, images: [{ id: 1 }, { id: 2 }] },
      { step: 1000, count: 1, images: [{ id: 3 }] }],
  });
  assert.deepEqual(visibleGalleryImages(groups, new Set(['s2000'])).map((i) => i.id),
    [1, 2]);
  assert.deepEqual(visibleGalleryImages(groups, new Set()).map((i) => i.id), []);
  // No filter = every fetched image (used to prune a stale selection).
  assert.deepEqual(visibleGalleryImages(groups, null).map((i) => i.id), [1, 2, 3]);
});

test('the summary states what is NOT shown when the answer was capped', () => {
  const full = runGallerySummary({ count: 12, shown: 12, truncated: false,
    groups: [{}, {}] });
  assert.match(full, /12 images across 2 steps, most-trained first\./);
  assert.doesNotMatch(full, /Showing/);

  const cut = runGallerySummary({ count: 400, shown: 240, truncated: true,
    groups: [{}, {}, {}] });
  assert.match(cut, /Showing the newest 240/);

  assert.match(runGallerySummary({ count: 0, groups: [] }),
    /Nothing generated from this run yet/);
});

test('checkpoint notes come from the payload and outlive the files', () => {
  // The saves are gone from disk, so the node has no pills at all — the notes
  // must still be there, newest step first, including a step with no image.
  const data = { checkpoint_notes: [{ step: 3500, note: 'shipping this one' },
    { step: 2000, note: 'soft eyes' }, { step: 1000, note: '  ' }] };
  assert.deepEqual(checkpointNotes(data, { checkpoints: [] }),
    [{ step: 3500, note: 'shipping this one' }, { step: 2000, note: 'soft eyes' }]);

  // A payload from before the field falls back to the node, still ordered.
  assert.deepEqual(checkpointNotes({}, { checkpoints: [
    { step: 500, note: 'early' }, { step: 2500, note: 'better' }, { step: 1000 }] }),
  [{ step: 2500, note: 'better' }, { step: 500, note: 'early' }]);

  assert.deepEqual(checkpointNotes(null, null), []);
});

test('the honest gap survives the widening, worded for its scope', () => {
  assert.equal(unlinkedNote(0), null);
  assert.match(unlinkedNote(881, 'run'), /^881 older test images could not be traced back to a run/);
  assert.match(unlinkedNote(881), /traced back to a checkpoint/);
  for (const scope of ['run', 'checkpoint']) {
    assert.match(unlinkedNote(1, scope), /they are in the Test Studio\./);
    assert.match(unlinkedNote(1, scope), /^1 older test image /);   // singular
  }
});
